// Copies the pure TypeScript helpers and the bundled datasets from web/ into src/shared/,
// and the ML API client into src/ml/.
// Run after changing web/src/lib or web/src/data: `npm run sync`.
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const web = join(here, '..', '..', 'web', 'src');
const out = join(here, '..', 'src', 'shared');
const banner = '// GENERATED by scripts/sync-shared.mjs from web/src. Edit the web source instead.\n';

rmSync(out, { recursive: true, force: true });
mkdirSync(join(out, 'data'), { recursive: true });
for (const file of ['types.ts', 'format.ts', 'i18n.ts', 'facts.ts', 'metrics.ts', 'insight.ts', 'chart.ts', 'geo.ts', 'pin.ts']) {
  const source = readFileSync(join(web, 'lib', file), 'utf8');
  writeFileSync(join(out, file), banner + source);
}
cpSync(join(web, 'data'), join(out, 'data'), { recursive: true });

// The ML API client: the same three files Teo ships in mobile-kit/ml/.
const mlOut = join(here, '..', 'src', 'ml');
rmSync(mlOut, { recursive: true, force: true });
mkdirSync(mlOut, { recursive: true });
for (const file of ['types.ts', 'client.ts', 'usePrediction.ts']) {
  const source = readFileSync(join(web, 'lib', 'ml', file), 'utf8');
  writeFileSync(join(mlOut, file), banner + source);
}
console.log('synced shared code and data into src/shared, ML client into src/ml');
