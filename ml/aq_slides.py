"""Charts and numbers for slides 4 and 6, from ml/models/aq_meta.json and the latest ml/reports/aq_*.json.

    uv run --group ml python -m ml.aq_slides

Writes docs/slides/mae_24h.png, docs/slides/mae_by_horizon.png and docs/slides/numbers.md."""
from __future__ import annotations

import json
import sys
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt

sys.stdout.reconfigure(encoding="utf-8", errors="replace")
ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "slides"
INK, MODEL, PERS, CAMS = "#1b1b1f", "#d6334a", "#9aa0a6", "#4fa3d6"


def latest_report() -> dict:
    reports = sorted((ROOT / "ml" / "reports").glob("aq_*.json"))
    return json.loads(reports[-1].read_text(encoding="utf-8"))


def style(ax):
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    ax.tick_params(labelsize=12)


def main() -> None:
    rep = latest_report()
    meta = rep["meta"]
    live = json.loads((ROOT / "ml" / "models" / "aq_meta.json").read_text(encoding="utf-8"))
    ep_path = ROOT / "web" / "src" / "data" / "aq_episode.json"
    score = json.loads(ep_path.read_text(encoding="utf-8")).get("score") if ep_path.exists() else None
    OUT.mkdir(parents=True, exist_ok=True)

    # Slide 6: one bar chart, 24 h ahead, VT and all BG.
    fig, ax = plt.subplots(figsize=(10, 5.6), dpi=150)
    groups = [("Велико Търново\nзима 2025/26", meta["mae_vt"]), ("цяла България\nзима 2025/26", meta["mae"])]
    sb_path = ROOT / "data" / "processed" / "scoreboard_replay.json"
    season = None
    if sb_path.exists():
        c = json.loads(sb_path.read_text(encoding="utf-8"))
        season = c["runs"][c["chosen"]]
        m = season["mae_pm25_next_day"]
        groups += [("Велико Търново\nноември 2026*", m["vt"]), ("цяла България\nноември 2026*", m["bg"])]
    w = 0.26
    for k, (label, m) in enumerate(groups):
        for j, (key, name, color) in enumerate((("model", "нашият модел", MODEL), ("persistence", "„утре = днес“", PERS),
                                                 ("cams", "CAMS (Copernicus)", CAMS))):
            x = k + (j - 1) * w
            ax.bar(x, m[key], w * 0.92, color=color, label=name if k == 0 else None)
            ax.text(x, m[key] + 0.3, f"{m[key]:.1f}", ha="center", fontsize=13, color=INK)
    ax.set_xticks(range(len(groups)), [g[0] for g in groups], fontsize=14)
    ax.set_ylabel("средна грешка PM2.5, µg/m³ (по-ниско = по-добре)", fontsize=12)
    gain_vt = 100 * (1 - meta["mae_vt"]["model"] / meta["mae_vt"]["cams"])
    ax.set_title(f"Прогноза за утре: с {gain_vt:.0f}% по-точно от Copernicus за ВТ (зима 2025/26)",
                 fontsize=15, loc="left")
    if season:
        blh = ("без прогноза за слоя на смесване" if season["blh"] == "none"
               else "слоят на смесване е измерен (ERA5)")
        fig.text(0.01, 0.015, f"* {season['from'][8:]}–{season['to'][8:]}.11.2026, с прогнозата за времето, каквато е била "
                 f"тогава ({blh}).\n  Модели, обучени преди зима 2025/26: тези седмици не са виждани.\n  CAMS (вход и "
                 f"сравнение) е от архива – по-нов от момента на прогнозата, еднакво за двете колони.", fontsize=10, color=INK)
    ax.set_ylim(0, 1.15 * max(m[k] for _, m in groups for k in ("model", "persistence", "cams")))
    ax.legend(frameon=False, fontsize=12, ncol=3, loc="upper left")
    style(ax)
    fig.tight_layout(rect=(0, 0.1 if season else 0, 1, 1))
    fig.savefig(OUT / "mae_24h.png")

    # Error by horizon.
    fig, ax = plt.subplots(figsize=(10, 5.2), dpi=150)
    rows = rep["mae_by_horizon_bg"]
    hs = [r["h"] for r in rows]
    ax.plot(hs, [r["model"] for r in rows], color=MODEL, lw=3, marker="o", label="нашият модел")
    ax.plot(hs, [r["persistence"] for r in rows], color=PERS, lw=2.5, marker="o", label="„утре = днес“")
    ax.plot(hs, [r["cams"] for r in rows], color=CAMS, lw=2.5, ls="--", marker="o", label="CAMS (Copernicus)")
    ax.set_xlabel("часове напред", fontsize=12)
    ax.set_ylabel("средна грешка PM2.5, µg/m³", fontsize=12)
    ax.set_xticks(hs)
    ax.set_title("Грешка според това колко напред гледаме (цяла България)", fontsize=15, loc="left")
    ax.legend(frameon=False, fontsize=12)
    style(ax)
    fig.tight_layout()
    fig.savefig(OUT / "mae_by_horizon.png")

    vt, bg = meta["mae_vt"], meta["mae"]
    lines = [
        "# Slide numbers (generated by ml/aq_slides.py)", "",
        f"- Model `{live['name']}` ({live.get('algorithm', live.get('algo'))}), trained {live['trained_at']}: "
        f"{live['trained_rows']:,} training rows from {live['sensors']} BG sensors "
        f"({live['sensor_hours']:,} hourly sensor readings, heating seasons Oct 2023 → today).",
        f"- Holdout {meta['holdout']} (never seen in training). PM2.5 MAE at 24 h, µg/m³:",
        f"  - VT: model {vt['model']}, persistence {vt['persistence']}, CAMS {vt['cams']} → "
        f"{100 * (1 - vt['model'] / vt['cams']):.0f}% better than CAMS, {100 * (1 - vt['model'] / vt['persistence']):.0f}% better than persistence",
        f"  - BG: model {bg['model']}, persistence {bg['persistence']}, CAMS {bg['cams']} → "
        f"{100 * (1 - bg['model'] / bg['cams']):.0f}% better than CAMS",
        f"- Next-day PM10 > 50 (EU limit) F1: model {rep['exceedance_f1']['model']:.2f}, CAMS {rep['exceedance_f1']['cams']:.2f}, "
        f"persistence {rep['exceedance_f1']['persistence']:.2f}",
        f"- 10–90% band covers {100 * rep['band_coverage_10_90']:.0f}% of outcomes.",
        f"- VT, winter 2025/26: {rep['vt_exceedance_days_holdout']} days with PM10 > 50; days at EAQI ≥ 3 (sensitive alert): "
        f"{rep['vt_alert_days_holdout']['sensitive']['observed']} of {rep['vt_alert_days_holdout']['sensitive']['days']}; "
        f"≥ 4 (everyone): {rep['vt_alert_days_holdout']['general']['observed']}.",
        "- Top feature groups: " + ", ".join(f"{g['label_en']} {100 * g['share']:.0f}%" for g in meta["importance"][:5]),
    ]
    if season:
        sv, sg = season["mae_pm25_next_day"]["vt"], season["mae_pm25_next_day"]["bg"]
        lines.append(
            f"- This season ({season['from']} → {season['to']}, {season['days']} days, forecast weather, BLH {season['blh']}"
            f"{': boundary layer observed' if season['blh'] == 'era5' else ''}; CAMS input and baseline from the CAMS archive, "
            f"fresher than the issue time), PM2.5 MAE next-day hours: "
            f"VT model {sv['model']} vs CAMS {sv['cams']} → {100 * (1 - sv['model'] / sv['cams']):.0f}% better "
            f"(persistence {sv['persistence']}); BG model {sg['model']} vs CAMS {sg['cams']} → "
            f"{100 * (1 - sg['model'] / sg['cams']):.0f}% better (persistence {sg['persistence']}).")
    if score:
        a, c = score["model_alert"], score["cams"]
        lines.append(
            f"- Day-before warnings for sensitive groups in VT (EAQI ≥ 3), {score['days']} days, {score['bad_days']} bad: "
            f"model caught {a['hits']}, {a['false_alarms']} false alarms; CAMS caught {c['hits']}, {c['false_alarms']} false alarms. "
            f"On the 10 worst days: model warned {score['worst10']['model_warned']}, CAMS {score['worst10']['cams_warned']}.")
    (OUT / "numbers.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
